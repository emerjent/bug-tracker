#!/usr/bin/env node
/**
 * Generates app/theme-dark.css (#277): Tailwind's own palette, mirrored.
 *
 * Every page is written with light-mode classes (bg-white, text-slate-900,
 * bg-teal-50 text-teal-800, …). Rather than adding a dark: twin to each of
 * those hundreds of classes, dark mode redefines the colour variables those
 * utilities read. Each scale is mirrored end to end (50 ↔ 950, 100 ↔ 900,
 * …), so any pair that has contrast in light mode keeps it in dark mode,
 * and a light tint with dark text becomes a dark tint with light text.
 *
 * Neutrals are shifted one step so surfaces stack the way dark UIs expect:
 * the page is the darkest, cards (white) sit one step above it, and chips
 * and hovers one step above that.
 *
 *   node scripts/generate-dark-palette.mjs   (after upgrading Tailwind)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const themeCss = readFileSync(require.resolve("tailwindcss/theme.css"), "utf8");

const palette = {};
for (const [, family, shade, value] of themeCss.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  (palette[family] ??= {})[shade] = value.trim();
}

/**
 * Brand colour (#459). The app's primary accent is written as Tailwind
 * `teal-*` classes. To brighten it without touching hundreds of class names,
 * the teal scale is re-pointed at another Tailwind scale here, once, and both
 * themes are generated from that: app/theme-brand.css (light) and the dark
 * mirror below. Change BRAND_SOURCE and re-run this script to try another.
 */
const BRAND_FAMILY = "teal";
const BRAND_SOURCE = "green";

const SHADES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];
const NEUTRALS = new Set(["slate", "gray", "zinc", "neutral", "stone"]);

/** Mirror for colours; neutrals stack page < card < chip. */
function darkShade(family, shade) {
  if (NEUTRALS.has(family)) {
    const map = {
      50: "950", 100: "800", 200: "700", 300: "600", 400: "500", 500: "400",
      600: "300", 700: "200", 800: "100", 900: "50", 950: "50",
    };
    return map[shade];
  }
  return SHADES[SHADES.length - 1 - SHADES.indexOf(shade)];
}

palette[BRAND_FAMILY] = { ...palette[BRAND_SOURCE] };

const lines = [];
for (const family of Object.keys(palette).sort()) {
  for (const shade of SHADES) {
    if (!palette[family][shade]) continue;
    lines.push(`  --color-${family}-${shade}: ${palette[family][darkShade(family, shade)]};`);
  }
}
// White is the card surface in light mode; in dark mode it sits one step
// above the page (slate-950), the way slate-900 does. Black stays black.
lines.push(`  --color-white: ${palette.slate["900"]};`);
lines.push("  --background: " + palette.slate["950"] + ";");
lines.push("  --foreground: " + palette.slate["50"] + ";");
lines.push("  color-scheme: dark;");

const block = lines.join("\n");
const out = `/*
 * GENERATED by scripts/generate-dark-palette.mjs: don't edit by hand (#277).
 *
 * Dark mode applies when the user picked Dark (data-theme="dark" on <html>),
 * or picked System (no data-theme, or "system") and the device prefers dark.
 * A user who picked Light (data-theme="light") always gets light.
 * Screens only: paper always prints in the light palette.
 */
@media screen and (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block.replace(/^/gm, "  ")}
  }
}

@media screen {
  :root[data-theme="dark"] {
${block.replace(/^/gm, "  ")}
  }
}
`;
writeFileSync(new URL("../app/theme-dark.css", import.meta.url), out);

const brand = SHADES.filter((shade) => palette[BRAND_FAMILY][shade])
  .map((shade) => `  --color-${BRAND_FAMILY}-${shade}: ${palette[BRAND_FAMILY][shade]};`)
  .join("\n");
writeFileSync(
  new URL("../app/theme-brand.css", import.meta.url),
  `/*
 * GENERATED by scripts/generate-dark-palette.mjs: don't edit by hand (#459).
 *
 * Brand colour token: the \`${BRAND_FAMILY}-*\` utilities used for buttons,
 * accents and highlights read this scale, re-pointed at Tailwind's
 * \`${BRAND_SOURCE}\` scale. app/theme-dark.css mirrors the same values.
 */
@theme {
${brand}
}
`,
);
console.log(`app/theme-brand.css: ${BRAND_FAMILY} -> ${BRAND_SOURCE}`);
console.log(`app/theme-dark.css: ${lines.length} variables`);
